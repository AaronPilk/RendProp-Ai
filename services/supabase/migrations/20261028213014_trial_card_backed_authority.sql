create function public.media_account_committed_capacity(p_ref text)
returns bigint language sql stable security definer set search_path='' as $$
 select case when cash_source='card_backed_auto_refill' then card_authorized_cents
  else cash_paid_cents end from public.media_account_reserves where receipt_ref=p_ref;
$$;
revoke all on function public.media_account_committed_capacity(text) from public,anon,authenticated;
grant execute on function public.media_account_committed_capacity(text) to service_role;

-- Existing purchases use their immutable paid-cash receipt. Card-backed
-- conversion consumes its already-held liability even if a later provider
-- verification expires; expiry only prevents NEW purchase-sheet holds.
do $patch$ declare d text;a text;b text;
begin
 d:=pg_get_functiondef('public.provision_media_delivery_budget(uuid,text,uuid,timestamptz,timestamptz,bigint,bigint,bigint,jsonb,jsonb,text,text)'::regprocedure);
 a:='a.cash_paid_cents-a.allocated_org_cents-(select sum(value::numeric)from jsonb_each_text(a.reserves))<total';
 b:='public.media_account_committed_capacity(a.receipt_ref)-a.allocated_org_cents-(select sum(value::numeric)from jsonb_each_text(a.reserves))<total';
 if (length(d)-length(replace(d,a,'')))/length(a)<>1 then
  raise exception 'Review changed media account capacity predecessor';end if;
 execute replace(d,a,b);
end $patch$;

-- Match the exact $500 trial pool to the same $1,000 operator authority as
-- the media reserve. A card row can NEVER satisfy the old cash branch.
do $patch$ declare d text;a text;b text;
begin
 d:=pg_get_functiondef('public.subscription_trial_media_template_ready(uuid)'::regprocedure);
 a:='if a.cash_paid_cents+legacy_future>50000 then return false;end if;';
 b:=$body$
 if p.funding_basis='card_backed_auto_refill' then
  if a.cash_source<>'card_backed_auto_refill' or p.card_authority_id is null
   or a.card_authority_id is distinct from p.card_authority_id
   or not public.trial_card_authority_active(p.card_authority_id)
   or p.funded_cents<>50000
   or a.card_authorized_cents+legacy_future+
    coalesce((select sum(f.sponsored_cents) from public.serving_funding f
     join public.trial_card_budget_authorities authority on authority.id=p.card_authority_id
     where f.source='app_review' and f.starts_at<authority.ends_at
       and f.retention_ends_at>authority.starts_at),0)>50000
  then return false;end if;
 elsif p.funding_basis='paid_cash' then
  if a.cash_source='card_backed_auto_refill' or a.cash_paid_cents+legacy_future>50000
  then return false;end if;
 else return false;end if;$body$;
 if (length(d)-length(replace(d,a,'')))/length(a)<>1 then
  raise exception 'Review changed trial media funding predecessor';end if;
 execute replace(d,a,b);
end $patch$;

-- Readiness copy must not assert that an owner paid cash when the independent
-- source of authority is a capped card-backed operating budget.
do $patch$ declare d text;a text;b text;
begin
 d:=pg_get_functiondef('public.subscription_trial_activation_readiness()'::regprocedure);
 a:='Owner-approved $1,000 existing-business-cash launch allocation recorded; first 100 seven-day trial holds are bounded to $500 total and shared, QA, and legacy future commitments fit the other $500';
 b:='Owner-approved $1,000 launch budget backed by actual paid cash or independently verified card-backed auto-refill; first 100 seven-day trial holds are bounded to $500 and shared media, QA and legacy future commitments fit the other $500';
 if (length(d)-length(replace(d,a,'')))/length(a)<>1 then
  raise exception 'Review changed trial readiness funding copy';end if;
 execute replace(d,a,b);
end $patch$;

commit;
