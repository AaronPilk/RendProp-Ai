-- Every new trial admission needs a recently reviewed provider/card state.
-- The digests refer to private evidence; they are not proofs generated by SQL.
-- A verification cannot authorize new holds for more than 24 hours without
-- a new provider readback, while each hold has seven days of coverage.
create table public.trial_card_provider_verifications (
 id uuid primary key default gen_random_uuid(),
 authority_id uuid not null references public.trial_card_budget_authorities(id),
 verified_at timestamptz not null default now(), valid_until timestamptz not null,
 kie_auto_refill_enabled boolean not null,
 fal_auto_refill_enabled boolean not null,
 kie_card_on_file boolean not null,
 fal_card_on_file boolean not null,
 kie_refill_amount_cents integer not null check(kie_refill_amount_cents between 1 and 50000),
 fal_refill_amount_cents integer not null check(fal_refill_amount_cents between 1 and 50000),
 kie_evidence_sha256 text not null check(kie_evidence_sha256~'^[a-f0-9]{64}$'),
 fal_evidence_sha256 text not null check(fal_evidence_sha256~'^[a-f0-9]{64}$'),
 payment_method_evidence_sha256 text not null check(payment_method_evidence_sha256~'^[a-f0-9]{64}$'),
 check(valid_until>=verified_at+interval '7 days' and valid_until<=verified_at+interval '8 days')
);
create index trial_card_verification_latest
 on public.trial_card_provider_verifications(authority_id,verified_at desc);
alter table public.trial_card_provider_verifications enable row level security;
