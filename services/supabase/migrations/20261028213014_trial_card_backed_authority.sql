create function public.trial_card_authority_active(p_id uuid)
returns boolean language sql stable security definer set search_path='' as $$
 select exists(
  select 1 from public.trial_card_budget_authorities a
  join lateral (
   select v.* from public.trial_card_provider_verifications v
   where v.authority_id=a.id order by v.verified_at desc,id desc limit 1
  ) v on true
  where a.id=p_id and a.revoked_at is null and a.starts_at<=now()
   and a.ends_at>=now()+interval '97 days'
   and v.verified_at>=now()-interval '24 hours'
   and v.valid_until>=now()+interval '7 days'
   and v.kie_auto_refill_enabled and v.fal_auto_refill_enabled
   and v.kie_card_on_file and v.fal_card_on_file
 );
$$;
revoke all on function public.trial_card_authority_active(uuid) from public,anon,authenticated;
grant execute on function public.trial_card_authority_active(uuid) to service_role;

create function public.provision_trial_card_budget_authority(
 p_reference text,p_start timestamptz,p_end timestamptz,p_evidence text
) returns uuid language plpgsql security definer set search_path='' as $$
declare a public.trial_card_budget_authorities;
begin
 if current_setting('role',true) is distinct from 'service_role' then raise insufficient_privilege;end if;
 if p_reference is null or length(p_reference)not between 8 and 200
  or p_evidence is null or p_evidence!~'^[a-f0-9]{64}$'
  or p_start is null or p_end is null or p_start>now()+interval '5 minutes'
  or p_end<now()+interval '97 days' or p_end>p_start+interval '180 days'
 then raise exception 'RP400: Exact card-backed budget and evidence required';end if;
 perform pg_advisory_xact_lock(hashtextextended('trial-card-budget',72456));
 select * into a from public.trial_card_budget_authorities where reference=p_reference;
 if a.id is not null then
  if row(a.starts_at,a.ends_at,a.owner_budget_evidence_sha256,a.revoked_at)
   is distinct from row(p_start,p_end,p_evidence,null::timestamptz)
  then raise exception 'RP409: Card budget evidence is immutable';end if;
  return a.id;
 end if;
 insert into public.trial_card_budget_authorities(reference,account_id,total_authorized_cents,
  trial_hold_cap_cents,shared_media_qa_cap_cents,max_trial_holds,starts_at,ends_at,owner_budget_evidence_sha256)
 values(p_reference,'9c332c75b96cc642621dad5d86d4bf18',100000,50000,50000,100,p_start,p_end,p_evidence)
 returning id into a.id;
 return a.id;
end$$;
revoke all on function public.provision_trial_card_budget_authority(text,timestamptz,timestamptz,text) from public,anon,authenticated;
grant execute on function public.provision_trial_card_budget_authority(text,timestamptz,timestamptz,text) to service_role;

create function public.revoke_trial_card_budget_authority(p_authority uuid,p_evidence text)
returns boolean language plpgsql security definer set search_path='' as $$
declare a public.trial_card_budget_authorities;
begin
 if current_setting('role',true) is distinct from 'service_role' then raise insufficient_privilege;end if;
 if p_evidence is null or p_evidence!~'^[a-f0-9]{64}$'
 then raise exception 'RP400: Revocation evidence required';end if;
 perform pg_advisory_xact_lock(hashtextextended('subscription-trial-admission',72456));
 select * into a from public.trial_card_budget_authorities where id=p_authority for update;
 if a.id is null then raise exception 'RP404: Card-backed trial authority unavailable';end if;
 if a.revoked_at is not null then
  if a.revocation_evidence_sha256 is distinct from p_evidence
  then raise exception 'RP409: Card authority revocation evidence changed';end if;
  return false;
 end if;
 update public.trial_card_budget_authorities
  set revoked_at=now(),revocation_evidence_sha256=p_evidence where id=p_authority;
 return true;
end$$;
revoke all on function public.revoke_trial_card_budget_authority(uuid,text) from public,anon,authenticated;
grant execute on function public.revoke_trial_card_budget_authority(uuid,text) to service_role;

