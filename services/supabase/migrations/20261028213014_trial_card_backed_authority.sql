-- Optional card-backed operating authority for the FIRST public trial cohort.
-- This is an authorization to incur up to $1,000, not a paid-cash receipt or
-- a representation that $1,000 has been deposited with Kie, FAL or a bank.
-- Existing paid-cash trial paths and all pre-existing holds remain unchanged.
-- Nothing is enabled, funded or verified by applying this migration.
begin;

create table public.trial_card_budget_authorities (
 id uuid primary key default gen_random_uuid(),
 reference text not null unique check(length(reference) between 8 and 200),
 account_id text not null check(account_id='9c332c75b96cc642621dad5d86d4bf18'),
 total_authorized_cents bigint not null check(total_authorized_cents=100000),
 trial_hold_cap_cents bigint not null check(trial_hold_cap_cents=50000),
 shared_media_qa_cap_cents bigint not null check(shared_media_qa_cap_cents=50000),
 max_trial_holds integer not null check(max_trial_holds=100),
 starts_at timestamptz not null, ends_at timestamptz not null,
 owner_budget_evidence_sha256 text not null unique check(owner_budget_evidence_sha256~'^[a-f0-9]{64}$'),
 revoked_at timestamptz,
 revocation_evidence_sha256 text check(revocation_evidence_sha256~'^[a-f0-9]{64}$'),
 created_at timestamptz not null default now(),
 check(ends_at>=starts_at+interval '97 days' and ends_at<=starts_at+interval '180 days')
);
