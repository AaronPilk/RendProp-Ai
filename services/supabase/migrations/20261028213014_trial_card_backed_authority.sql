create function public.provision_trial_card_media_account_reserve(
 p_authority uuid,p_ref text,p_start timestamptz,p_end timestamptz,
 p_authorized_cents bigint,p_evidence text,p_tariff jsonb,p_reserves jsonb
) returns jsonb language plpgsql security definer set search_path='' as $$
declare a public.trial_card_budget_authorities;old public.media_account_reserves;
 k text;n numeric;total numeric:=0;boundary numeric;
begin
 if current_setting('role',true) is distinct from 'service_role' then raise insufficient_privilege;end if;
 if not public.trial_card_authority_active(p_authority) then
  raise exception 'RP402: Verified card-backed trial authority is unavailable';end if;
 select * into a from public.trial_card_budget_authorities where id=p_authority for update;
 if p_ref is null or length(p_ref)not between 8 and 200
  or p_evidence is null or p_evidence!~'^[a-f0-9]{64}$'
  or p_start is null or p_end is null or p_start>now()+interval '5 minutes'
  or p_start<a.starts_at or p_end<a.ends_at or p_end>p_start+interval '180 days'
  or p_authorized_cents is null or p_authorized_cents not between 1 and a.shared_media_qa_cap_cents
  or jsonb_typeof(p_tariff)is distinct from 'object'
  or jsonb_typeof(p_reserves)is distinct from 'object'
 then raise exception 'RP400: Bounded card-backed media coverage required';end if;
 foreach k in array array['r2_a_cents_per_million','r2_b_cents_per_million','worker_cents_per_million',
  'worker_cpu_cents_per_million_ms','edge_cents_per_million','db_cents','logs_cents','storage_cents_per_gb_month'] loop
  if jsonb_typeof(p_tariff->k)is distinct from 'number' then raise exception 'RP400: Complete media tariff required';end if;
  n:=(p_tariff->>k)::numeric;
  if n<0 or n>1000000000 then raise exception 'RP400: Invalid media tariff';end if;
 end loop;
 if (select count(*) from jsonb_object_keys(p_tariff))<>8
  or (p_tariff->>'r2_a_cents_per_million')::numeric<450
  or (p_tariff->>'r2_b_cents_per_million')::numeric<36
  or (p_tariff->>'worker_cents_per_million')::numeric<30
  or (p_tariff->>'worker_cpu_cents_per_million_ms')::numeric<2
  or (p_tariff->>'edge_cents_per_million')::numeric<200
  or (p_tariff->>'db_cents')::numeric<=0
  or (p_tariff->>'storage_cents_per_gb_month')::numeric<1.5
 then raise exception 'RP400: Supplier floor and fixed compute evidence required';end if;
 foreach k in array array['storage','delivery','compute','email','support','retention','uncertainty'] loop
  if jsonb_typeof(p_reserves->k)is distinct from 'number' then raise exception 'RP400: Complete media reserves required';end if;
  n:=(p_reserves->>k)::numeric;
  if n<0 or n<>trunc(n) or n>1000000000 then raise exception 'RP400: Integer media reserves required';end if;
  total:=total+n;
 end loop;
 boundary:=ceil(extract(epoch from(p_end-p_start))/2592000)*
  ((p_tariff->>'r2_a_cents_per_million')::numeric+
   (p_tariff->>'r2_b_cents_per_million')::numeric+
   (p_tariff->>'worker_cents_per_million')::numeric);
 if (select count(*) from jsonb_object_keys(p_reserves))<>7 or total>p_authorized_cents
  or (p_reserves->>'delivery')::numeric<ceil(boundary)
  or (p_reserves->>'compute')::numeric<
   (p_tariff->>'db_cents')::numeric+(p_tariff->>'logs_cents')::numeric+
   ceil(extract(epoch from(p_end-p_start))/2592000)*
   ((p_tariff->>'edge_cents_per_million')::numeric+
    (p_tariff->>'worker_cpu_cents_per_million_ms')::numeric)
 then raise exception 'RP402: Card authorization does not cover account media costs';end if;
 perform pg_advisory_xact_lock(hashtextextended('media-account:'||a.account_id,72453));
 select * into old from public.media_account_reserves where receipt_ref=p_ref for update;
 if old.receipt_ref is not null then
  if row(old.card_authority_id,old.starts_at,old.ends_at,old.card_authorized_cents,
         old.card_evidence_sha256,old.tariff,old.reserves)
   is distinct from row(p_authority,p_start,p_end,p_authorized_cents,p_evidence,p_tariff,p_reserves)
  then raise exception 'RP409: Card media receipt is immutable';end if;
  return jsonb_build_object('reserved',true,'replay',true);end if;
 insert into public.media_account_reserves(receipt_ref,account_id,cash_source,cash_evidence_sha256,
  starts_at,ends_at,cash_paid_cents,tariff,reserves,card_authority_id,card_authorized_cents,card_evidence_sha256)
 values(p_ref,a.account_id,'card_backed_auto_refill',null,p_start,p_end,0,p_tariff,p_reserves,
  p_authority,p_authorized_cents,p_evidence);
 return jsonb_build_object('reserved',true,'replay',false);
end$$;
