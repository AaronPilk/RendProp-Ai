import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "node:http";
import { build } from "vite";
import { chromium, expect } from "@playwright/test";
const root = fileURLToPath(new URL("../", import.meta.url));
const artifacts = await mkdtemp(join(tmpdir(), "rendprop-listing-finish-")), dist = join(artifacts, "dist");
const receipt = { proof: "Real listing UI with isolated imported-media/state fixtures. No camera, live account, provider call or publication.", checks: [], errors: [], externalRequests: [] };
let browser, server, page;
try {
  await build({ configFile: false, root, publicDir: false, logLevel: "error", build: { outDir: dist, rollupOptions: { input: join(root, "tests/listing-finish-fixture.html") } } });
  server = createServer(async (request, response) => { const path = resolve(dist, `.${new URL(request.url, "http://localhost").pathname}`); if (!path.startsWith(`${dist}/`)) return response.writeHead(400).end(); try { response.setHeader("Content-Type", ({ ".html": "text/html", ".js": "application/javascript", ".css": "text/css" })[extname(path)] ?? "application/octet-stream"); response.end(await readFile(path)); } catch { response.writeHead(404).end(); } });
  await new Promise(done => server.listen(0, "127.0.0.1", done));
  const origin = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true, executablePath: process.env.STUDIO_BROWSER_EXECUTABLE });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, serviceWorkers: "block" });
  await context.route("**/*", route => { if (new URL(route.request().url()).origin === origin && route.request().method() === "GET") return route.continue(); receipt.externalRequests.push(route.request().url()); return route.abort(); });
  page = await context.newPage(); page.setDefaultTimeout(6000); page.on("pageerror", error => receipt.errors.push(error.message));
  const open = async scenario => { await page.goto(`${origin}/tests/listing-finish-fixture.html?scenario=${scenario}`); await expect(page.getByRole("heading", { name: "Finish this listing", exact: true })).toBeVisible(); };
  const guide = () => page.getByRole("region", { name: "Finish this listing", exact: true });
  const noMutations = async () => assert.equal((await page.evaluate(() => window.finishFixture.calls())).filter(call => call.method !== "GET").length, 0);
  await open("photos");
  await expect(guide().getByRole("heading", { name: "Your photos are ready to review" })).toBeVisible();
  await guide().locator(".lw-finish-next").getByRole("button", { name: "Review and download photos" }).click();
  await expect(page.getByRole("tab", { name: "1 Media" })).toHaveAttribute("aria-selected", "true");
  await guide().getByRole("button", { name: "Review details", exact: true }).click();
  await expect(page.getByLabel("Address or property name")).toHaveValue("10 Oak Street");
  await guide().getByRole("button", { name: "Open Reel Studio", exact: true }).click();
  await expect(page.getByRole("status", { name: "Opened tool" })).toHaveText("reel:20000000-0000-4000-8000-000000000002");
  await guide().getByRole("button", { name: "Open AI Photo Studio", exact: true }).click();
  await expect(page.getByRole("status", { name: "Opened tool" })).toHaveText("studio:20000000-0000-4000-8000-000000000002");
  assert.equal(await guide().locator('[data-step="review"]').getAttribute("data-status"), "review");
  await noMutations(); receipt.checks.push("Photos-only listing navigates to Media, Details, existing Reel and Photo Studio with correct listing; review is not fabricated; no mutation");
  await page.getByRole("tab", { name: "1 Media" }).click();
  await page.screenshot({ path: join(artifacts, "finish-listing-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  await page.screenshot({ path: join(artifacts, "finish-listing-mobile.png"), fullPage: true });
  receipt.checks.push("Desktop and 390px layout captured, no horizontal overflow");
  await page.setViewportSize({ width: 1440, height: 1100 });
  await open("qc");
  await expect(guide().getByRole("heading", { name: "Check the generated results" })).toBeVisible();
  await guide().locator(".lw-finish-next").getByRole("button", { name: "Open accuracy review" }).click();
  await expect(page.getByRole("status", { name: "Opened tool" })).toHaveText("animate:20000000-0000-4000-8000-000000000002");
  await noMutations(); receipt.checks.push("Generated video points to existing accuracy-review tool without granting approval or publishing");
  await open("readonly");
  await expect(guide().getByRole("button", { name: "Open accuracy review", exact: true })).toBeDisabled();
  await expect(guide().getByRole("button", { name: "Open Reel Studio", exact: true })).toBeDisabled();
  await expect(guide().getByRole("button", { name: "Open AI Photo Studio", exact: true })).toBeDisabled();
  await guide().getByRole("button", { name: "View results needing review" }).click();
  await guide().getByRole("button", { name: "Review details", exact: true }).click();
  await expect(page.getByRole("button", { name: "Save property", exact: true })).toBeDisabled();
  await noMutations(); receipt.checks.push("Read-only member can inspect and navigate while creation, accuracy approval and save controls remain disabled");
  await open("processing");
  await expect(guide().getByRole("progressbar", { name: "Tour preparation progress" })).toHaveAttribute("value", "0.4");
  await guide().getByRole("button", { name: "View render progress" }).click();
  await expect(page.getByRole("tab", { name: "2 Create & publish" })).toHaveAttribute("aria-selected", "true");
  await noMutations(); receipt.checks.push("Active job shows reported progress and opens job status without starting another render");
  await open("failed");
  await expect(guide().getByRole("heading", { name: "A render needs attention" })).toBeVisible();
  await noMutations(); receipt.checks.push("Failed job has an actionable issue state, no automatic retry");
  await open("live");
  await expect(guide().getByRole("link", { name: "Open live property" })).toHaveAttribute("href", "https://rendprop.com/f/fixture-oak");
  await guide().locator(".lw-finish-next").getByRole("button", { name: "View sharing options" }).click();
  await expect(page.getByRole("link", { name: "Open MLS tour" })).toHaveAttribute("href", "https://rendprop.com/u/fixture-oak");
  await noMutations(); receipt.checks.push("Existing published tour links and sharing options derive from published render state");
  await open("error");
  await expect(guide().getByRole("heading", { name: "Check the latest property status" })).toBeVisible();
  await expect(guide().locator(".lw-finish-checklist")).toHaveCount(0);
  await expect(guide().getByRole("button", { name: "Reload listing status" })).toBeVisible();
  receipt.checks.push("Incomplete load has no fabricated readiness checklist and offers reload");
  await open("loading");
  await expect(guide()).toHaveAttribute("aria-busy", "true");
  await expect(guide().locator(".lw-finish-checklist")).toHaveCount(0);
  await expect(guide().locator(".lw-finish-next button")).toHaveCount(0);
  receipt.checks.push("Loading state makes no empty-media, ready or publish claim");
  assert.deepEqual(receipt.errors, []); assert.deepEqual(receipt.externalRequests, []); receipt.status = "passed";
} catch (error) { receipt.status = "failed"; receipt.failure = error.stack ?? String(error); process.exitCode = 1; if (page) await page.screenshot({ path: join(artifacts, "failure.png"), fullPage: true }).catch(() => {}); }
finally { await browser?.close(); if (server) await new Promise(done => server.close(done)); await writeFile(join(artifacts, "receipt.json"), JSON.stringify(receipt, null, 2)); console.log(JSON.stringify({ ...receipt, artifacts }, null, 2)); }
